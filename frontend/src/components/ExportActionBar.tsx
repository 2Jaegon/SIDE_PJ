import React, { useState } from 'react';
import { Copy, Check, Download, Sparkles, FileText } from 'lucide-react';
import { DeskData } from './OfficeFloor';

interface ExportActionBarProps {
  query: string;
  content: string;
  team: DeskData[];
  promptCoachTip: string;
  showRecipeCard: boolean;
  onToggleRecipeCard: () => void;
}

export const ExportActionBar: React.FC<ExportActionBarProps> = ({
  query,
  content,
  team,
  promptCoachTip,
  showRecipeCard,
  onToggleRecipeCard,
}) => {
  const [copied, setCopied] = useState(false);

  // 1. 전체 마크다운 파일 다운로드
  const handleDownloadMarkdown = () => {
    const teamHeader = team.map((t) => `- **${t.character_name}** (${t.name}): ${t.badge_label}`).join('\n');
    const mdContent = `# Munder Difflin AI Office 합동 작업 보고서\n\n` +
      `> **의뢰 과제:** ${query}\n` +
      `> **작성 일시:** ${new Date().toLocaleString()}\n\n` +
      `## 👥 참여 에이전트 스쿼드\n${teamHeader}\n\n` +
      `---\n\n` +
      `${content}\n\n` +
      `---\n\n` +
      `## 💡 Michael's AI 평준화 코칭 (Prompt Recipe)\n${promptCoachTip}\n\n` +
      `*Generated by Munder Difflin AI Office (SkillBridge)*\n`;

    const blob = new Blob([mdContent], { type: 'text/markdown;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    const sanitizedTitle = query.slice(0, 15).replace(/[^a-zA-Z0-9가-힣]/g, '_');
    link.download = `munder-difflin-report-${sanitizedTitle}.md`;
    link.click();
    URL.revokeObjectURL(url);
  };

  // 2. 본문 클립보드 복사
  const handleCopyContent = () => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="flex flex-wrap items-center justify-between gap-3 p-3.5 rounded-2xl bg-slate-900/80 border border-slate-800 text-xs">
      <div className="flex items-center gap-2">
        <FileText className="w-4 h-4 text-emerald-400" />
        <span className="font-bold text-white">업무 산출물 옵션</span>
        <span className="text-slate-500">|</span>
        <span className="text-slate-400 text-[11px]">마크다운 다운로드 및 레시피 공유 지원</span>
      </div>

      <div className="flex items-center gap-2">
        {/* 본문 복사 */}
        <button
          onClick={handleCopyContent}
          className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 transition-colors"
        >
          {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
          <span>{copied ? '복사됨!' : '본문 복사'}</span>
        </button>

        {/* 마크다운 다운로드 */}
        <button
          onClick={handleDownloadMarkdown}
          className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-700 text-slate-200 transition-colors"
        >
          <Download className="w-3.5 h-3.5 text-indigo-400" />
          <span>.md 파일 다운로드</span>
        </button>

        {/* 프롬프트 레시피 카드 토글 */}
        <button
          onClick={onToggleRecipeCard}
          className={`flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl font-medium transition-all ${
            showRecipeCard
              ? 'bg-amber-500 text-slate-950 font-bold shadow-md shadow-amber-500/20'
              : 'bg-indigo-600/90 hover:bg-indigo-500 text-white shadow-md shadow-indigo-600/20'
          }`}
        >
          <Sparkles className="w-3.5 h-3.5" />
          <span>{showRecipeCard ? '레시피 카드 닫기' : '공유용 레시피 카드 보기'}</span>
        </button>
      </div>
    </div>
  );
};
